#!/usr/bin/env python3
"""Embed the public README verbatim for offline installation and viewing."""
import argparse
import hashlib
from pathlib import Path
import re

root = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--readme', type=Path, default=root / 'README.md')
parser.add_argument('--version-header', type=Path, default=root / 'JournalVersion.h')
parser.add_argument('--output', type=Path, default=root / 'JournalGuideText.h')
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
match = re.search(r'^\s*#define\s+TJ_VERSION\s+"([0-9]+(?:\.[0-9]+)*)"', args.version_header.read_text(), re.M)
if not match:
    parser.error('JournalVersion.h must define a numeric dotted TJ_VERSION')
body = 'Tiny Journal generated user guide | V. ' + match[1] + '\n' + args.readme.read_text(encoding='utf-8')
if not body.endswith('\n'):
    body += '\n'
if len(body.encode('utf-8')) > 65536:
    parser.error('offline guide exceeds the 64 KiB bounded reader')
delimiter = 'TJ' + hashlib.sha256(body.encode('utf-8')).hexdigest()[:10]
header = '// Generated by tools/generate-guide.py; edit README.md instead.\n#pragma once\n#include <stddef.h>\n#include <pgmspace.h>\n'
header += 'static const char TJ_GUIDE_TEXT[] PROGMEM = R"' + delimiter + '(' + body + ')' + delimiter + '";\n'
header += 'static constexpr size_t TJ_GUIDE_LENGTH = sizeof(TJ_GUIDE_TEXT) - 1;\n'
if args.check:
    if not args.output.exists() or args.output.read_text(encoding='utf-8') != header:
        parser.error('JournalGuideText.h is stale; run tools/generate-guide.py')
else:
    with args.output.open('w', encoding='utf-8', newline='\n') as output:
        output.write(header)
